/**
 * Discover available containers from Docker (cross-process discovery)
 * 
 * This enables Worker to find containers warmed by API process!
 * Uses lock file to check availability instead of labels.
 */
async function discoverAvailableContainer(
    poolKey: string, 
    config: PoolConfig
): Promise<BlackboxContainer | null> {
    try {
        // Query Docker for all containers with matching pool key
        const result = execSync(
            `docker ps -q --filter "label=grader.pool=blackbox" --filter "label=grader.pool.key=${poolKey}" 2>/dev/null || true`,
            { encoding: 'utf-8', timeout: 5000 }
        ).trim();
        
        if (!result) return null;
        
        const containerIds = result.split('\n').filter(Boolean);
        if (containerIds.length === 0) return null;
        
        // Check each container for availability (no lock file = available)
        for (const containerId of containerIds) {
            try {
                // Check if lock file exists (if it does, container is in-use)
                const lockCheck = execSync(
                    `docker exec ${containerId} test -f /tmp/.pool-lock && echo locked || echo available`,
                    { encoding: 'utf-8', timeout: 3000 }
                ).trim();
                
                if (lockCheck !== 'available') continue;
                
                // Try to acquire by creating lock file atomically
                execSync(
                    `docker exec ${containerId} sh -c "test ! -f /tmp/.pool-lock && touch /tmp/.pool-lock"`,
                    { timeout: 3000, stdio: 'ignore' }
                );
                
                // Verify we got the lock
                const verifyLock = execSync(
                    `docker exec ${containerId} test -f /tmp/.pool-lock && echo locked || echo available`,
                    { encoding: 'utf-8', timeout: 3000 }
                ).trim();
                
                if (verifyLock !== 'locked') continue;
                
                // Get container info
                const inspectJson = execSync(
                    `docker inspect ${containerId}`,
                    { encoding: 'utf-8', timeout: 5000 }
                );
                const info = JSON.parse(inspectJson)[0];
                const name = info.Name.replace(/^\//, '');
                const workDir = info.Config.Labels['grader.pool.workdir'] || join(tmpdir(), name);
                const runtime = (info.Config.Labels['grader.pool.runtime'] || 'node') as 'node' | 'python' | 'go' | 'rust';
                
                console.log(`[BlackboxPool] Discovered container: ${name} (pool: ${poolKey})`);
                
                return {
                    name,
                    runtime,
                    image: config.image,
                    workDir,
                    createdAt: new Date(info.Created),
                    lastUsedAt: new Date(),
                    useCount: 0,
                    isReleased: false,
                    dependencyHash: computeDependencyHash(config.dependencies),
                };
            } catch {
                // This container didn't work, try next
                continue;
            }
        }
        
        return null;
    } catch {
        // Discovery failed, will create new container
        return null;
    }
}

async function validateContainer(container: BlackboxContainer): Promise<boolean> {
    try {
        const result = execSync(`docker inspect -f '{{.State.Running}}' ${container.name}`, {
            encoding: 'utf-8',
            timeout: 5000,
        }).trim();
        
        if (result !== 'true') return false;
        
        // Check responsive
        await execInContainer(container.name, 'echo ok', 5000);
        
        // Check use count
        if (container.useCount >= MAX_CONTAINER_USES) {
            console.log(`[BlackboxPool] Container ${container.name} reached max uses`);
            return false;
        }
        
        return true;
    } catch {
        return false;
    }
}

/**
 * Acquire a container from pool (or create new one)
 * 
 * With generatedFiles + installCommand, dependencies are PRE-INSTALLED:
 * - Python: requirements.txt already installed → just copy main.py
 * - Node: node_modules ready → just copy src files
 * - Go/Rust: modules cached → just copy source
 */
export async function acquireBlackboxContainer(config: {
    runtime: 'node' | 'python' | 'go' | 'rust';
    image: string;
    dependencies: Record<string, string>;
    generatedFiles?: Record<string, string>;  // Files like requirements.txt, package.json
    installCommand?: string;  // e.g., "pip install -r requirements.txt"
}): Promise<BlackboxContainer> {
    // Include generatedFiles hash in pool key for better cache hit
    const filesHash = config.generatedFiles 
        ? computeDependencyHash(config.generatedFiles)
        : '';
    const poolKey = `${config.runtime}:${computeDependencyHash(config.dependencies)}:${filesHash.substring(0, 8)}`;
    
    return await poolMutex.runExclusive(async () => {
        let pool = containerPools.get(poolKey);
        
        // Create pool if doesn't exist
        if (!pool) {
            pool = {
                available: [],
                inUse: new Set(),
                config: {
                    runtime: config.runtime,
                    image: config.image,
                    dependencies: config.dependencies,
                    generatedFiles: config.generatedFiles,  // <-- Store for warmup!
                    installCommand: config.installCommand,   // <-- Store for warmup!
                },
                lastActivityAt: Date.now(),
            };
            containerPools.set(poolKey, pool);
            console.log(`[BlackboxPool] Created new pool: ${poolKey}`);
        }
        
        pool.lastActivityAt = Date.now();
        
        // Try to get an available container from in-memory pool (deps already installed!)
        while (pool.available.length > 0) {
            const container = pool.available.pop()!;
            
            if (!(await validateContainer(container))) {
                // Container unhealthy, destroy it
                await destroyContainer(container);
                continue;
            }

            // Cross-process safety: mark in-use via /tmp/.pool-lock (in-memory pool alone isn't shared).
            // If we can't acquire the lock, assume another process grabbed it and skip.
            try {
                execSync(
                    `docker exec ${container.name} sh -c "test ! -f /tmp/.pool-lock && touch /tmp/.pool-lock"`,
                    { timeout: 3000, stdio: 'ignore' }
                );
            } catch {
                continue;
            }

            try {
                await resetContainer(container);
            } catch (e) {
                console.warn(`[BlackboxPool] Reset failed for ${container.name}, destroying:`, e);
                await destroyContainer(container);
                continue;
            }

            pool.inUse.add(container.name);
            console.log(`[BlackboxPool] Acquired pooled container: ${container.name} (deps pre-installed ✅)`);
            return container;
        }
        
        // Cross-process discovery: Look for containers created by other processes (e.g., API → Worker)
        const discoveredContainer = await discoverAvailableContainer(poolKey, config);
        if (discoveredContainer) {
            try {
                await resetContainer(discoveredContainer);
            } catch (e) {
                console.warn(`[BlackboxPool] Reset failed for discovered ${discoveredContainer.name}, destroying:`, e);
                await destroyContainer(discoveredContainer);
                // Fall through to create a new container
            }

            if (await validateContainer(discoveredContainer)) {
                pool.inUse.add(discoveredContainer.name);
                console.log(`[BlackboxPool] Discovered container from Docker: ${discoveredContainer.name} (cross-process ✅)`);
                return discoveredContainer;
            }
        }
        
        // No available container, create new one (this installs deps)
        console.log(`[BlackboxPool] No available container, creating new one for ${config.runtime}...`);
        const newContainer = await createContainer(pool.config);
        pool.inUse.add(newContainer.name);
        console.log(`[BlackboxPool] Created new container: ${newContainer.name} (deps installed ✅)`);
        return newContainer;
    });
}

/**
 * Release container back to pool
 */
export async function releaseBlackboxContainer(container: BlackboxContainer): Promise<void> {
    if (container.isReleased) {
        console.warn(`[BlackboxPool] Container ${container.name} already released`);
        return;
    }
    
    container.isReleased = true;
    
    const poolKey = getPoolKey(container.runtime, {});  // We need the full deps but don't have them
    
    await poolMutex.runExclusive(async () => {
        // Find the pool this container belongs to
        for (const [key, pool] of containerPools) {
            if (pool.inUse.has(container.name)) {
                pool.inUse.delete(container.name);
                
                // Check if still healthy
                if (await validateContainer(container)) {
                    pool.available.push(container);
                    
                    // Mark as available (remove lock file for cross-process discovery)
                    try {
                        execSync(
                            `docker exec ${container.name} rm -f /tmp/.pool-lock`,
                            { timeout: 5000, stdio: 'ignore' }
                        );
                    } catch {
                        // Ignore
                    }
                    
                    console.log(`[BlackboxPool] Released container: ${container.name} (available: ${pool.available.length})`);
                } else {
                    await destroyContainer(container);
                }
                return;
            }
        }
        
        // Container not in any pool, just destroy
        console.warn(`[BlackboxPool] Container ${container.name} not found in any pool, destroying`);
        await destroyContainer(container);
    });
}

/**
 * Get pool status
 */
export function getBlackboxPoolStatus(): {
    pools: Array<{
        key: string;
        runtime: string;
        available: number;
        inUse: number;
    }>;
    totalContainers: number;
} {
    const pools: Array<{ key: string; runtime: string; available: number; inUse: number }> = [];
    let totalContainers = 0;
    
    for (const [key, pool] of containerPools) {
        pools.push({
            key,
            runtime: pool.config.runtime,
            available: pool.available.length,
            inUse: pool.inUse.size,
        });
        totalContainers += pool.available.length + pool.inUse.size;
    }
    
    return { pools, totalContainers };
}

/**
 * Cleanup idle pools
 */
export async function cleanupIdleBlackboxPools(): Promise<number> {
    let cleanedCount = 0;
    
    await poolMutex.runExclusive(async () => {
        const now = Date.now();
        
        for (const [key, pool] of containerPools) {
            // Check if pool is idle
            if (pool.inUse.size === 0 && now - pool.lastActivityAt > CONTAINER_IDLE_TIMEOUT) {
                console.log(`[BlackboxPool] Cleaning up idle pool: ${key}`);
                
                for (const container of pool.available) {
                    await destroyContainer(container);
                    cleanedCount++;
                }
                
                containerPools.delete(key);
            }
        }
    });
    
    if (cleanedCount > 0) {
        console.log(`[BlackboxPool] Cleaned up ${cleanedCount} idle containers`);
    }
    
    return cleanedCount;
}

/**
 * Drain all pools (shutdown)
 */
export async function drainBlackboxPools(): Promise<void> {
    console.log('[BlackboxPool] Draining all pools...');
    
    await poolMutex.runExclusive(async () => {
        for (const [key, pool] of containerPools) {
            for (const container of pool.available) {
                await destroyContainer(container);
            }
            // Note: in-use containers will be cleaned up when they're released
        }
        containerPools.clear();
    });
    
    console.log('[BlackboxPool] All pools drained');
}


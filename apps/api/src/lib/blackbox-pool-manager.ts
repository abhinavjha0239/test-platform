// ============ Docker Helpers ============

async function dockerExec(args: string[], timeoutMs: number): Promise<{ stdout: string; stderr: string }> {
    return new Promise((resolve, reject) => {
        const proc = spawn('docker', args, { stdio: ['ignore', 'pipe', 'pipe'] });
        let stdout = '';
        let stderr = '';

        const timer = setTimeout(() => {
            proc.kill('SIGKILL');
            reject(new Error(`Docker timeout: docker ${args.slice(0, 8).join(' ')}...`));
        }, timeoutMs);

        proc.stdout.on('data', (d) => (stdout += d.toString()));
        proc.stderr.on('data', (d) => (stderr += d.toString()));

        proc.on('close', (code) => {
            clearTimeout(timer);
            const exitCode = code ?? 1;
            if (exitCode === 0) return resolve({ stdout, stderr });
            reject(new Error(`Docker command failed (${exitCode}): docker ${args.join(' ')}\n${stdout}\n${stderr}`));
        });

        proc.on('error', (err) => {
            clearTimeout(timer);
            reject(err);
        });
    });
}

async function execInContainer(containerName: string, command: string, timeoutMs = 30000): Promise<string> {
    const { stdout, stderr } = await dockerExec(['exec', containerName, 'sh', '-c', command], timeoutMs);
    return stdout + stderr;
}


/**
 * Blackbox Pool Manager
 * 
 * Manages reusable container pools for HTTP-mode (blackbox) and Playwright grading.
 * Instead of creating fresh containers for each grading job, we reuse pre-warmed
 * containers with dependencies already installed.
 * 
 * This eliminates the ~60-120s npm install / pip install overhead per job.
 */

